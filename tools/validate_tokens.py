#!/usr/bin/env python3
"""Валидатор дизайн-токенов уровня 1.

Проверяет:
1. Синхронизацию design/tokens/pixel-art-theme.yaml с apps/web/src/theme/tokens.css и packages/world-engine/src/theme/tokens.ts;
2. Наличие автогенерируемых заголовков;
3. Наличие метеорологических токенов с префиксом --meteo-* и METEO_COLORS;
4. Отсутствие несогласованных цветов.
"""

from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
YAML_PATH = ROOT / "design/tokens/pixel-art-theme.yaml"
CSS_PATH = ROOT / "apps/web/src/theme/tokens.css"
TS_PATH = ROOT / "packages/world-engine/src/theme/tokens.ts"


def validate_tokens() -> list[str]:
    errors: list[str] = []

    if not YAML_PATH.exists():
        errors.append(f"Файл токенов {YAML_PATH} не найден")
        return errors

    if not CSS_PATH.exists():
        errors.append(f"Сгенерированный файл {CSS_PATH} не найден")
    else:
        css_text = CSS_PATH.read_text(encoding="utf-8")
        if "THIS FILE IS AUTOGENERATED" not in css_text:
            errors.append(f"{CSS_PATH} не содержит метку автогенерации")
        if "--meteo-cold-front" not in css_text or "--meteo-warm-front" not in css_text:
            errors.append(f"{CSS_PATH} не содержит метеорологические переменные --meteo-*")
        if "--color-sky-night-0" not in css_text:
            errors.append(f"{CSS_PATH} не содержит мастер-палитру --color-*")

    if not TS_PATH.exists():
        errors.append(f"Сгенерированный файл {TS_PATH} не найден")
    else:
        ts_text = TS_PATH.read_text(encoding="utf-8")
        if "THIS FILE IS AUTOGENERATED" not in ts_text:
            errors.append(f"{TS_PATH} не содержит метку автогенерации")
        if "METEO_COLORS" not in ts_text or "coldFront" not in ts_text:
            errors.append(f"{TS_PATH} не содержит типизированную константу METEO_COLORS")
        if "WORLD_PALETTE" not in ts_text or "UI_COLORS" not in ts_text:
            errors.append(f"{TS_PATH} не содержит WORLD_PALETTE или UI_COLORS")
        if not re.search(r"0x[0-9A-Fa-f]{6}", ts_text):
            errors.append(f"{TS_PATH} не содержит числовых шестнадцатеричных значений для Phaser")

    return errors


def main() -> int:
    errors = validate_tokens()
    if errors:
        print("Проверка дизайн-токенов завершилась с ошибками:")
        for err in errors:
            print(f" - {err}")
        return 1
    print("Проверка дизайн-токенов успешно завершена: CSS и TS токены согласованы с YAML.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
