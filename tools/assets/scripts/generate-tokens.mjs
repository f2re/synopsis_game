#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT = resolve(__dirname, '../../..');

const YAML_PATH = resolve(ROOT, 'design/tokens/pixel-art-theme.yaml');
const CSS_OUT = resolve(ROOT, 'apps/web/src/theme/tokens.css');
const TS_OUT = resolve(ROOT, 'packages/world-engine/src/theme/tokens.ts');

function parseSimpleYaml(content) {
  const lines = content.split('\n');
  const result = {};
  let currentSection = null;
  let currentSubsection = null;

  for (let rawLine of lines) {
    const line = rawLine.replace(/\r$/, '');
    if (!line.trim() || line.trim().startsWith('#')) continue;

    const indent = line.search(/\S/);
    const trimmed = line.trim();

    if (indent === 0 && trimmed.endsWith(':')) {
      currentSection = trimmed.slice(0, -1);
      result[currentSection] = {};
      currentSubsection = null;
    } else if (indent === 2 && trimmed.endsWith(':') && currentSection) {
      currentSubsection = trimmed.slice(0, -1);
      result[currentSection][currentSubsection] = {};
    } else if (indent === 2 && currentSection && trimmed.includes(':')) {
      const colonIdx = trimmed.indexOf(':');
      const key = trimmed.slice(0, colonIdx).trim();
      let val = trimmed.slice(colonIdx + 1).trim();
      val = val.replace(/^["']|["']$/g, '');
      result[currentSection][key] = val;
    } else if (indent === 4 && currentSection && currentSubsection && trimmed.startsWith('-')) {
      if (!Array.isArray(result[currentSection][currentSubsection])) {
        result[currentSection][currentSubsection] = [];
      }
      let val = trimmed.slice(1).trim().replace(/^["']|["']$/g, '');
      result[currentSection][currentSubsection].push(val);
    } else if (indent === 4 && currentSection && currentSubsection && trimmed.includes(':')) {
      const colonIdx = trimmed.indexOf(':');
      const key = trimmed.slice(0, colonIdx).trim();
      let val = trimmed.slice(colonIdx + 1).trim();
      val = val.replace(/^["']|["']$/g, '');
      result[currentSection][currentSubsection][key] = val;
    }
  }

  return result;
}

function hexToPhaserNumber(hex) {
  return '0x' + hex.replace('#', '').toUpperCase();
}

function kebabCase(str) {
  return str.replace(/_/g, '-');
}

function camelCase(str) {
  return str.replace(/_([a-z0-9])/g, (_, g) => g.toUpperCase());
}

function generateTokens() {
  const yamlRaw = readFileSync(YAML_PATH, 'utf-8');
  const data = parseSimpleYaml(yamlRaw);

  const masterPalette = data.master_palette || {};
  const uiTokens = data.ui || {};
  const meteoTokens = data.meteo || {};

  // 1. Generate CSS
  const cssLines = [];
  cssLines.push('/* THIS FILE IS AUTOGENERATED FROM design/tokens/pixel-art-theme.yaml. DO NOT EDIT DIRECTLY. */');
  cssLines.push('/* Generated by tools/assets/scripts/generate-tokens.mjs */\n');
  cssLines.push(':root {');

  cssLines.push('  /* ========================================================================== */');
  cssLines.push('  /* 1. Мастер-палитра мира (World Master Palette v2)                         */');
  cssLines.push('  /* ========================================================================== */');
  for (const [ramp, colors] of Object.entries(masterPalette)) {
    if (Array.isArray(colors)) {
      colors.forEach((hex, idx) => {
        cssLines.push(`  --color-${kebabCase(ramp)}-${idx}: ${hex};`);
      });
    } else if (typeof colors === 'object') {
      for (const [k, hex] of Object.entries(colors)) {
        cssLines.push(`  --color-${kebabCase(ramp)}-${kebabCase(k)}: ${hex};`);
      }
    }
  }

  cssLines.push('\n  /* ========================================================================== */');
  cssLines.push('  /* 2. Семантический интерфейс (UI Tokens)                                   */');
  cssLines.push('  /* ========================================================================== */');
  for (const [k, hex] of Object.entries(uiTokens)) {
    cssLines.push(`  --color-ui-${kebabCase(k)}: ${hex};`);
  }

  cssLines.push('\n  /* ========================================================================== */');
  cssLines.push('  /* 3. Метеорологические токены (ТОЛЬКО для карт и приземных схем)           */');
  cssLines.push('  /* ========================================================================== */');
  for (const [k, val] of Object.entries(meteoTokens)) {
    if (val.startsWith('#')) {
      cssLines.push(`  --meteo-${kebabCase(k)}: ${val};`);
    }
  }

  cssLines.push('\n  /* ========================================================================== */');
  cssLines.push('  /* 4. Пиксельная типографика v2 (Font Families)                             */');
  cssLines.push('  /* ========================================================================== */');
  cssLines.push('  --font-display: "PixCyrillic", monospace;');
  cssLines.push('  --font-ui: "PixCyrillic", monospace;');
  cssLines.push('  --font-dense: "PixCyrillic-Dense", monospace;');
  cssLines.push('  --font-mono: "PressStart2P", monospace;');
  cssLines.push('}\n');

  mkdirSync(dirname(CSS_OUT), { recursive: true });
  writeFileSync(CSS_OUT, cssLines.join('\n'), 'utf-8');
  console.log(`✓ Записаны CSS токены в ${CSS_OUT}`);

  // 2. Generate TypeScript for Phaser/world-engine
  const tsLines = [];
  tsLines.push('// THIS FILE IS AUTOGENERATED FROM design/tokens/pixel-art-theme.yaml. DO NOT EDIT DIRECTLY.');
  tsLines.push('// Generated by tools/assets/scripts/generate-tokens.mjs\n');

  tsLines.push('/**');
  tsLines.push(' * Мастер-палитра мира уровня 1 (числовые HEX значения для Phaser 4/WebGL).');
  tsLines.push(' */');
  tsLines.push('export const WORLD_PALETTE = {');
  for (const [ramp, colors] of Object.entries(masterPalette)) {
    if (Array.isArray(colors)) {
      colors.forEach((hex, idx) => {
        tsLines.push(`  ${camelCase(ramp)}${idx}: ${hexToPhaserNumber(hex)},`);
      });
    } else if (typeof colors === 'object') {
      for (const [k, hex] of Object.entries(colors)) {
        tsLines.push(`  ${camelCase(ramp)}_${camelCase(k)}: ${hexToPhaserNumber(hex)},`);
      }
    }
  }
  tsLines.push('} as const;\n');

  tsLines.push('/**');
  tsLines.push(' * Семантические цвета интерфейса в числовом формате Phaser.');
  tsLines.push(' */');
  tsLines.push('export const UI_COLORS = {');
  for (const [k, hex] of Object.entries(uiTokens)) {
    tsLines.push(`  ${camelCase(k)}: ${hexToPhaserNumber(hex)},`);
  }
  tsLines.push('} as const;\n');

  tsLines.push('/**');
  tsLines.push(' * Метеорологические цвета (строго зарезервированы для карт и схем станций).');
  tsLines.push(' */');
  tsLines.push('export const METEO_COLORS = {');
  for (const [k, val] of Object.entries(meteoTokens)) {
    if (val.startsWith('#')) {
      tsLines.push(`  ${camelCase(k)}: ${hexToPhaserNumber(val)},`);
    }
  }
  tsLines.push('} as const;\n');

  tsLines.push('export type WorldPaletteColor = keyof typeof WORLD_PALETTE;');
  tsLines.push('export type UiColor = keyof typeof UI_COLORS;');
  tsLines.push('export type MeteoColor = keyof typeof METEO_COLORS;\n');

  mkdirSync(dirname(TS_OUT), { recursive: true });
  writeFileSync(TS_OUT, tsLines.join('\n'), 'utf-8');
  console.log(`✓ Записаны TS токены в ${TS_OUT}`);
}

generateTokens();
